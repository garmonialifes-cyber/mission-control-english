    ex:`${a} × ${b}: периметр ${2*(a+b)}, площадь ${a*b}\n${a+1} × ${b-1}: периметр ${2*(a+b)}, площадь ${(a+1)*(b-1)}\nПериметр тот же, площадь другая`,

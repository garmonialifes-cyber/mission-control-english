GEN.g_unit=()=>{
  const sets=[
    {from:'feet',to:'inches',k:12,n:R(2,12)},
    {from:'yards',to:'feet',k:3,n:R(2,15)},
    {from:'meters',to:'centimeters',k:100,n:R(2,9)},
    {from:'kilometers',to:'meters',k:1000,n:R(2,9)},
    {from:'kilograms',to:'grams',k:1000,n:R(2,9)},
    {from:'pounds',to:'ounces',k:16,n:R(2,10)},
    {from:'gallons',to:'quarts',k:4,n:R(2,12)},
    {from:'centimeters',to:'millimeters',k:10,n:R(3,30)}
  ];
  const s=pick(sets), right=s.n*s.k;
  return {
    q:`${s.n} ${s.from} = ___ ${s.to}`,
    o:opts(right,s.n+s.k,Math.round(s.n/s.k*100)/100,right*10),
    why:`Переходя к более мелкой единице, число растёт — значит нужно умножение, а не деление.`,
    rule:`В одной единице ${s.from} содержится ${s.k} ${s.to}. Когда переходишь к более мелким единицам, их становится больше, поэтому умножаешь. В обратную сторону — делишь. Проверить направление можно здравым смыслом: мелких единиц всегда больше, чем крупных.`,
    ex:`1 ${s.from} = ${s.k} ${s.to}\n${s.n} × ${s.k} = ${right} ${s.to}`,
    again:`Подумай, что крупнее. ${s.from} крупнее, чем ${s.to}, значит их меньше — и при переводе число должно вырасти.`,
    up:(()=>{const m=R(2,9);return{q:`А сколько ${s.to} в ${m} ${s.from}? (число)`,a:String(m*s.k)}})()
  };
};


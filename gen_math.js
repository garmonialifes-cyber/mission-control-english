/* ── умножение многозначного на однозначное ── */
GEN.g_mult=()=>{
  const a=R(112,987), b=R(3,9), right=a*b;
  const d=[...String(a)].map(Number);
  const steps=[];let carry=0,s='';
  for(let i=d.length-1;i>=0;i--){
    const p=d[i]*b+carry;
    steps.push(`${b} × ${d[i]} = ${d[i]*b}${carry?', плюс перенос '+carry+' = '+p:''} → пишем ${p%10}${p>9?', держим '+Math.floor(p/10):''}`);
    s=(p%10)+s;carry=Math.floor(p/10);
  }
  if(carry)s=carry+s;
  const approx=Math.round(a/100)*100*b;
  return {
    q:`${b} × ${a} = ?`,
    o:opts(right,right-10*b,right+100,a*b-d[0]*b),
    why:`Скорее всего потерялся перенос. Когда произведение в разряде больше девяти, последняя цифра остаётся на месте, а остальное переезжает в следующий разряд и там прибавляется.`,
    rule:`Умножение столбиком идёт справа налево, разряд за разрядом. В каждом разряде сначала умножаешь, потом прибавляешь перенос — именно в таком порядке. Перенос это не лишняя цифра, а десятки, которые не поместились в своём разряде. Пропустил хоть один — ответ уедет на сотни.`,
    ex:`${b} × ${a} по шагам:\n`+steps.join('\n')+`\nОтвет: ${right}`,
    again:`Прикинь результат заранее: ${a} примерно ${Math.round(a/100)*100}, значит ответ около ${approx}. Если получилось далеко от этого — ищи ошибку в переносах.`,
    up:(()=>{const x=R(3,9),y=R(112,899);return{q:`${x} × ${y} = ?`,a:String(x*y)}})()
  };
};


GEN.g_money=()=>{
  const price=+(R(150,900)/100).toFixed(2), qty=R(2,5);
  const paid=Math.ceil(price*qty)+R(1,5);
  const total=+(price*qty).toFixed(2), change=+(paid-total).toFixed(2);
  const two=Math.random()<.5;
  if(two)return {
    q:`A notebook costs $${price.toFixed(2)}. Denis buys ${qty} of them and pays with $${paid}. How much change does he get?`,
    o:opts(`$${change.toFixed(2)}`,`$${total.toFixed(2)}`,`$${(paid-price).toFixed(2)}`,`$${(change+1).toFixed(2)}`),
    why:`Задача в два шага: сначала узнать стоимость покупки, и только потом вычесть её из отданных денег. Если вычесть сразу цену одной тетради, ответ будет не тот.`,
    rule:`В двухшаговой задаче важен порядок. Сначала считают общую сумму: цена умножается на количество. Потом ищут сдачу: из отданных денег вычитают эту сумму. Ошибка почти всегда в том, что один из шагов пропускают — поэтому полезно проговорить вслух, что считаешь на каждом шаге.`,
    ex:`Шаг 1: ${qty} × $${price.toFixed(2)} = $${total.toFixed(2)}\nШаг 2: $${paid} − $${total.toFixed(2)} = $${change.toFixed(2)}`,
    again:`В центах считать надёжнее: ${Math.round(price*100)} × ${qty} = ${Math.round(total*100)} центов, ${paid*100} − ${Math.round(total*100)} = ${Math.round(change*100)} центов.`,
    up:(()=>{const t=R(150,900)/100,pd=Math.ceil(t)+R(1,4);return{q:`Покупка стоит $${t.toFixed(2)}, дали $${pd}. Сдача? (число с точкой)`,a:(pd-t).toFixed(2)}})()
  };
  const a=+(R(100,800)/100).toFixed(2), b=+(R(100,800)/100).toFixed(2);
  return {
    q:`Denis buys a book for $${a.toFixed(2)} and a pen for $${b.toFixed(2)}. How much does he spend?`,
    o:opts(`$${(a+b).toFixed(2)}`,`$${Math.abs(a-b).toFixed(2)}`,`$${(a+b+1).toFixed(2)}`,`$${(a*b).toFixed(2)}`),
    why:`Слово «всего» означает сложение. Вычитание отвечало бы на вопрос, насколько одно дороже другого.`,
    rule:`В денежных задачах складывают по разрядам, выравнивая десятичные точки: центы с центами, доллары с долларами. Если центов набралось больше ста, один доллар переносится в целую часть — это обычный перенос, такой же как при сложении любых чисел.`,
    ex:`$${a.toFixed(2)} + $${b.toFixed(2)} = $${(a+b).toFixed(2)}`,
    again:`Переведи в центы: ${Math.round(a*100)} + ${Math.round(b*100)} = ${Math.round((a+b)*100)} центов, это $${(a+b).toFixed(2)}.`,
    up:(()=>{const A=R(100,500)/100,B=R(100,500)/100;return{q:`$${A.toFixed(2)} + $${B.toFixed(2)} = ? (число с точкой)`,a:(A+B).toFixed(2)}})()
  };
};


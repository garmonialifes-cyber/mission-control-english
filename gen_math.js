GEN.g_time=()=>{
  const h=R(1,10), m=pick([0,10,15,20,25,30,40,45,50]);
  const dur=R(25,180);
  const start=h*60+m, end=start+dur;
  const f=t=>`${Math.floor(t/60)%12||12}:${String(t%60).padStart(2,'0')}`;
  const kind=pick(['elapsed','distance']);
  if(kind==='elapsed')return {
    q:`A lesson starts at ${f(start)} and lasts ${dur} minutes. What time does it end?`,
    o:opts(f(end),f(end+30),f(end-30),f(start+Math.floor(dur/2))),
    why:`Минуты складывают отдельно от часов, и если их набралось больше шестидесяти, лишнее переходит в час.`,
    rule:`Время считают в шестидесятеричной системе: в часе 60 минут, а не 100. Поэтому при сложении минут переполнение наступает на шестидесяти, а не на сотне. Удобный приём — довести до круглого часа, а остаток добавить отдельно: так переносы делать проще, чем складывать всё разом.`,
    ex:`${f(start)} + ${dur} мин\n${dur} мин = ${Math.floor(dur/60)} ч ${dur%60} мин\nПолучаем ${f(end)}`,
    again:`Шагай по кругу часов: сначала до ближайшего целого часа, посмотри, сколько минут ушло, и добавь остаток.`,
    up:(()=>{const st=R(1,10)*60+pick([0,15,30,45]),dd=pick([35,50,55,70]);return{q:`Урок начался в ${f(st)} и шёл ${dd} минут. Во сколько кончился? (вида 3:20)`,a:f(st+dd)}})()
  };
  const speed=R(3,9), hours=R(2,6), dist=speed*hours;
  return {
    q:`A train travels ${speed} km every hour. How far does it go in ${hours} hours?`,
    o:opts(`${dist} km`,`${speed+hours} km`,`${dist*2} km`,`${Math.round(dist/2)} km`),
    why:`Одинаковые промежутки повторяются, значит нужно умножение, а не сложение расстояния со временем.`,
    rule:`Когда одна и та же величина повторяется несколько раз, умножение заменяет длинное сложение. Поезд проходит ${speed} км в каждый из ${hours} часов, значит путь это ${speed} × ${hours}. Складывать километры с часами нельзя — это разные величины, и их сумма не имеет смысла.`,
    ex:`${speed} км × ${hours} ч = ${dist} км\nПроверка сложением: ${Array(hours).fill(speed).join(' + ')} = ${dist}`,
    again:`Проверь обратным действием: ${dist} ÷ ${hours} = ${speed} км в час. Сошлось.`,
    up:(()=>{const v=R(4,12),t=R(2,7);return{q:`Поезд идёт ${v} км в час. Сколько пройдёт за ${t} часов? (число)`,a:String(v*t)}})()
  };
};


GEN.g_data=()=>{
  const n=pick([5,7]);
  let arr=Array.from({length:n-1},()=>R(2,20));
  arr.push(pick(arr));                       // чтобы мода точно была
  arr=arr.sort((a,b)=>a-b);
  const counts={}; arr.forEach(v=>counts[v]=(counts[v]||0)+1);
  const mode=+Object.keys(counts).sort((a,b)=>counts[b]-counts[a]||a-b)[0];
  const median=arr[Math.floor(arr.length/2)];
  const range=arr[arr.length-1]-arr[0];
  const what=pick(['mode','median','range']);
  const right={mode,median,range}[what];
  const nm={mode:'мода',median:'медиана',range:'размах'}[what];
  return {
    q:`Here is a set of numbers:\n${arr.join(', ')}\n\nWhat is the ${what}?`,
    o:opts(right,what==='mode'?median:mode,what==='range'?median:range,arr[0]),
    why:`Мода, медиана и размах отвечают на разные вопросы, и их легко перепутать. Здесь спрашивали ${nm}.`,
    rule:`Мода — значение, которое встречается чаще других. Медиана — то, что оказывается ровно посередине, когда числа выстроены по возрастанию. Размах — разница между самым большим и самым маленьким. Общее правило: прежде чем считать что-либо из этого, числа надо упорядочить, иначе медиана найдётся неверно.`,
    ex:`Упорядочили: ${arr.join(', ')}\nМода (чаще всех): ${mode}\nМедиана (посередине): ${median}\nРазмах (${arr[arr.length-1]} − ${arr[0]}): ${range}\nСпрашивали ${what} → ${right}`,
    again:`Привяжи слова к смыслу: móda — «модное», то есть самое частое. Медиана — «середина». Размах — насколько широко разбросаны числа.`,
    up:(()=>{const b2=Array.from({length:5},()=>R(2,30)).sort((x,y)=>x-y);return{q:`В наборе ${b2.join(', ')} чему равен размах? (число)`,a:String(b2[4]-b2[0])}})()
  };
};



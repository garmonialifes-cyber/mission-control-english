const opts=(right,...cands)=>{
  const out=[String(right)];
  for(const c of cands){const v=String(c);if(!out.includes(v)&&out.length<4)out.push(v)}
  let k=1;
  while(out.length<4){
    const m=String(right).match(/^(.*?)(-?\d+(?:\.\d+)?)(\D*)$/);
    let v;
    if(m){
      const dec=(m[2].split('.')[1]||'').length;
      v=m[1]+(parseFloat(m[2])+k*(k%2?1:-1)).toFixed(dec)+m[3];
    } else v=String(right)+'?'.repeat(k);
    if(!out.includes(v))out.push(v);
    k++; if(k>40)break;
  }
  return out;
};
